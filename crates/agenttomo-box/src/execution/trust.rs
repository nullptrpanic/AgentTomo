//! Only the launch helper changes mounts; the collector retains the real trust
//! store for upstream verification. Upper/work live in its private tmpfs.
use nix::{errno::Errno, libc};
use std::{
    ffi::CString,
    fs, io,
    os::unix::fs::DirBuilderExt,
    path::{Path, PathBuf},
};

const CERTS: &str = "/etc/ssl/certs";
const BUNDLE: &str = "ca-certificates.crt";

pub struct Overlay {
    directory: PathBuf,
}

impl Overlay {
    pub fn new(pem: &str) -> io::Result<Self> {
        let directory =
            std::env::temp_dir().join(format!("agenttomo-trust-{}", uuid::Uuid::new_v4()));
        fs::DirBuilder::new().mode(0o700).create(&directory)?;
        let overlay = Self { directory };
        // This is a public certificate, never a signing key. The helper reads
        // it before covering this directory with private tmpfs.
        fs::write(overlay.directory.join("ca.pem"), pem)?;
        Ok(overlay)
    }

    pub fn path(&self) -> &Path {
        &self.directory
    }
}

impl Drop for Overlay {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.directory);
    }
}

fn mount(
    source: &str,
    target: &Path,
    kind: &str,
    flags: libc::c_ulong,
    options: &str,
) -> io::Result<()> {
    let source = CString::new(source)?;
    let target = CString::new(target.as_os_str().as_encoded_bytes())?;
    let kind = CString::new(kind)?;
    let options = CString::new(options)?;
    Errno::result(unsafe {
        libc::mount(
            source.as_ptr(),
            target.as_ptr(),
            kind.as_ptr(),
            flags,
            options.as_ptr().cast(),
        )
    })?;
    Ok(())
}

pub fn install(directory: &Path) -> io::Result<()> {
    let install = || -> io::Result<()> {
        let ca = fs::read(directory.join("ca.pem"))?;
        let mut bundle = fs::read(Path::new(CERTS).join(BUNDLE))?;
        if !bundle.ends_with(b"\n") {
            bundle.push(b'\n');
        }
        bundle.extend_from_slice(&ca);
        Errno::result(unsafe { libc::unshare(libc::CLONE_NEWNS) })?;
        mount("", Path::new("/"), "", libc::MS_REC | libc::MS_PRIVATE, "")?;
        mount(
            "tmpfs",
            directory,
            "tmpfs",
            libc::MS_NOSUID | libc::MS_NODEV | libc::MS_NOEXEC,
            "size=4m,mode=0700",
        )?;
        let upper = directory.join("upper");
        let work = directory.join("work");
        fs::create_dir(&upper)?;
        fs::create_dir(&work)?;
        fs::write(upper.join(BUNDLE), bundle)?;
        fs::write(upper.join("agenttomo-task-ca.pem"), ca)?;
        // Escape-free paths are generated by us, not supplied as mount options.
        let options = format!(
            "lowerdir={CERTS},upperdir={},workdir={},userxattr",
            upper.display(),
            work.display()
        );
        mount(
            "overlay",
            Path::new(CERTS),
            "overlay",
            libc::MS_NOSUID | libc::MS_NODEV,
            &options,
        )?;
        Ok(())
    };
    install().map_err(|error| io::Error::other(format!("cannot inject task CA through OverlayFS into {CERTS}/{BUNDLE}: {error}; capture requires user/mount namespaces and OverlayFS (no fallback)")))
}
